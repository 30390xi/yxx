#!/usr/bin/env python3
"""Generate the DevTools-only public fixture route allowlist for the mini program."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent
index = json.loads((root / "fixtures/index.json").read_text(encoding="utf-8"))
routes = {
    "{}|{}|{}".format(row["method"], row["path"], row["query"]): True
    for row in index
    if row["method"] == "GET" or row["path"] in (
        "/base/app/v1/advert/selectAppAdvert",
        "/product/app/equityCard/selectPage",
        "/base/app/v1/contentRanking/selectRankingPage",
        "/base/app/v1/contentRanking/selectRankingDetails",
    )
}
target = root.parent / "runnable-miniapp/common/captured-api-routes.js"
source = '''// Generated by backend-java8/build_client_routes.py from captured public browse responses.
// POST routes are limited to the exact page call shapes verified against fixture fields.
var routes = ROUTES;
var originalBase = "https://eshopapi.zhiyousx.com/";
var localBase = "http://127.0.0.1:8787";

function canonicalQuery(query) {
  if (!query) return "";
  return query.split("&").filter(Boolean).map(function(part) {
    var separator = part.indexOf("=");
    var key = separator < 0 ? part : part.slice(0, separator);
    var value = separator < 0 ? "" : part.slice(separator + 1);
    return encodeURIComponent(decodeURIComponent(key.replace(/\\+/g, " ")))
      + "=" + encodeURIComponent(decodeURIComponent(value.replace(/\\+/g, " ")));
  }).sort().join("&");
}

function sameKeys(value, keys) {
  return value && typeof value === "object" && !Array.isArray(value)
    && Object.keys(value).sort().join("|") === keys.slice().sort().join("|");
}

function matchesKnownPost(path, data) {
  if (path === "/base/app/v1/advert/selectAppAdvert") {
    if (!sameKeys(data, ["typeList"]) || !Array.isArray(data.typeList) || data.typeList.length !== 6) return false;
    return data.typeList.slice().sort(function(a, b) { return a - b; }).join(",") === "9,12,13,14,16,17";
  }
  if (path === "/product/app/equityCard/selectPage") {
    return sameKeys(data, ["current", "size"]) && data.current === 1 && data.size === 11;
  }
  return false;
}

function resolve(method, endpoint, data, base) {
  if (base !== originalBase) return null;
  if (typeof endpoint !== "string" || endpoint.indexOf("://") !== -1) return null;
  method = String(method).toUpperCase();
  var parts = endpoint.split("?");
  var path = "/" + parts[0].replace(/^\\/+/, "");
  var query = parts.slice(1).join("?");
  if ((method === "POST" && (path === "/ai/aiEscort/session/create" ||
      (path === "/base/app/v1/sysParam/getSysParamForApp" && data && Array.isArray(data.keyList) &&
       ((data.keyList.length === 1 && data.keyList[0] === "XIAOQI_MENU") ||
        (data.keyList.length === 4 && ["GRAY_THEME_FLAG", "WX_VERSION", "HOME_PANDA_IS_SHOW", "XIAOQI_VERSION"].every(function(key) { return data.keyList.indexOf(key) !== -1; })))) ||
      path === "/ai/app/dialogue/add" || path === "/ai/app/dialogue/delete")) ||
      (method === "GET" && (path === "/ai/aiEscort/dialogue/record" || path === "/ai/planCard/queryTopRecent"))) {
    if (method === "GET" && data && typeof data === "object") {
      Object.keys(data).forEach(function(key) {
        if (data[key] !== undefined && data[key] !== null) query += (query ? "&" : "") + encodeURIComponent(key) + "=" + encodeURIComponent(String(data[key]));
      });
    }
    return localBase + path + (query ? "?" + query : "");
  }
  if (method === "POST") {
    if (!query && routes["POST|" + path + "|"] && matchesKnownPost(path, data)) return localBase + path;
    if ((path === "/base/app/v1/contentRanking/selectRankingPage" ||
         path === "/base/app/v1/contentRanking/selectRankingDetails") &&
        (data === undefined || data === null || data === "")) {
      try {
        return routes["POST|" + path + "|" + canonicalQuery(query)]
          ? localBase + path + (query ? "?" + query : "") : null;
      } catch (_) {
        return null;
      }
    }
    return null;
  }
  if (method !== "GET") return null;
  if (data && typeof data === "object" && !Array.isArray(data)) {
    Object.keys(data).forEach(function(key) {
      if (data[key] === undefined || data[key] === null) return;
      query += (query ? "&" : "") + encodeURIComponent(key) + "=" + encodeURIComponent(String(data[key]));
    });
  }
  try {
    return routes["GET|" + path + "|" + canonicalQuery(query)] ? localBase + path + (query ? "?" + query : "") : null;
  } catch (_) {
    return null;
  }
}

module.exports = { resolve: resolve, routes: routes };
'''.replace("ROUTES", json.dumps(routes, ensure_ascii=False, separators=(",", ":")))
target.write_text(source, encoding="utf-8")
print("Wrote {} public routes to {}".format(len(routes), target))
